
import os
import smtplib
import ssl
from pathlib import Path
from email.message import EmailMessage
from fk_common import env

BASE = Path(__file__).resolve().parent
REQUEST_ID = "REQ-20261023-2"
REPORT_DIR = BASE / "reports" / REQUEST_ID

# Find the existing Excel report.
workbooks = list(REPORT_DIR.glob("*.xlsx"))
if len(workbooks) != 1:
    raise RuntimeError(
        f"Expected exactly one Excel report; found {len(workbooks)}"
    )

# Read the original request to get the intended recipient.
import json

status = json.loads(
    (REPORT_DIR / "request_status.json").read_text(encoding="utf-8")
)

# The request status deliberately omits recipient_email.
# Set this environment variable to the recipient from the Google Form.
recipient = os.environ.get("RECIPIENT_EMAIL", "").strip()
if not recipient:
    raise RuntimeError(
        "Set RECIPIENT_EMAIL to the recipient from the Google Form."
    )

user = env("SMTP_USER")
password = env("SMTP_APP_PASSWORD")
if not user or not password:
    raise RuntimeError("SMTP configuration is incomplete.")

result = status.get("result", {})
product = status.get("product_name_resolved") or status.get("product_name")
start = status.get("start_date")
end = status.get("end_date")

msg = EmailMessage()
msg["From"] = user
msg["To"] = recipient
msg["Subject"] = f"Resent Flipkart review report: {product} ({start} to {end})"
msg["X-Request-ID"] = REQUEST_ID
msg.set_content(
    f"Resent existing report for request {REQUEST_ID}.\n"
    f"Product: {product}\n"
    f"Date range: {start} to {end}\n"
    f"Reviews collected: {result.get('valid_reviews', 0)}\n\n"
    "This workbook was generated by the original scraping run."
)

workbook = workbooks[0]
msg.add_attachment(
    workbook.read_bytes(),
    maintype="application",
    subtype="vnd.openxmlformats-officedocument.spreadsheetml.sheet",
    filename=workbook.name,
)

with smtplib.SMTP(
    env("SMTP_SERVER", "smtp.gmail.com"),
    int(env("SMTP_PORT", "587")),
    timeout=60,
) as smtp:
    smtp.ehlo()
    smtp.starttls(context=ssl.create_default_context())
    smtp.ehlo()
    smtp.login(user, password)
    smtp.send_message(msg)

print("Existing report email submitted successfully.")
print("Request ID:", REQUEST_ID)
print("Workbook:", workbook.name)
